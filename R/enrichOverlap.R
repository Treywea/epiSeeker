#' Calculate overlap significance of ChIP experiments based on their nearest gene annotation
#'
#' `N_OL` counts overlapping \emph{genes}, not peaks, so it can be larger than
#' the number of input peaks: a peak is annotated to its nearest gene, but the
#' same gene is reported once per peak and a peak region may overlap several
#' target genes (see issue #84 of ChIPseeker).
#'
#' @title enrichAnnoOverlap
#' @param queryPeak query bed file
#' @param targetPeak target bed file(s) or folder containing bed files
#' @param TxDb TxDb
#' @param pAdjustMethod pvalue adjustment method
#' @param chainFile chain file for liftOver
#' @param distanceToTSS_cutoff restrict nearest gene annotation by distance cutoff
#' @return data.frame
#' @importFrom stats p.adjust
#' @importFrom stats phyper
#' @export
#' @examples
#' if (interactive()) {
#'     require(TxDb.Hsapiens.UCSC.hg38.knownGene)
#'     txdb <- TxDb.Hsapiens.UCSC.hg38.knownGene
#'     peakfile <- system.file("extdata", "demo_peak.txt", package = "epiSeeker")
#'     enrichAnnoOverlap(peakfile, peakfile, txdb)
#' }
#' @importFrom rtracklayer import.chain
#' @importFrom rtracklayer liftOver
#' @importFrom yulab.utils get_cache_element
#' @importFrom yulab.utils update_cache_item
#' @author G Yu
enrichAnnoOverlap <- function(queryPeak, targetPeak, TxDb = NULL, pAdjustMethod = "BH", chainFile = NULL, distanceToTSS_cutoff = NULL) {
    TxDb <- loadTxDb(TxDb)

    query.anno <- annotateSeq(queryPeak,
        TxDb = TxDb,
        assignGenomicAnnotation = FALSE, annoDb = NULL, verbose = FALSE
    )


    if (is(targetPeak[1], "GRanges") || is(targetPeak[[1]], "GRanges")) {
        ## a single GRanges (or a list of GRanges) is accepted; a bare GRanges
        ## has to be wrapped in a list, the overlap code below works on a list
        ## of target peak sets and used to fail with
        ## "GRanges objects don't support [[, as.list(), lapply()"
        target.gr <- if (is(targetPeak, "GRanges")) list(targetPeak) else targetPeak
        targetFiles <- NULL
    } else {
        targetFiles <- parse_targetPeak_Param(targetPeak)
        target.gr <- lapply(targetFiles, loadPeak)
    }

    if (!is.null(chainFile)) {
        chain <- import.chain(chainFile)
        target.gr <- lapply(target.gr, liftOver, chain = chain)
    }

    target.anno <- lapply(target.gr, annotateSeq,
        TxDb = TxDb,
        assignGenomicAnnotation = FALSE, annoDb = NULL, verbose = FALSE
    )


    if (!is.null(distanceToTSS_cutoff)) {
        query.anno <- dropAnno(query.anno, distanceToTSS_cutoff)
        target.anno <- lapply(target.anno, dropAnno, distanceToTSS_cutoff = distanceToTSS_cutoff)
    }

    # epiSeekerEnv <- get("epiSeekerEnv", envir=.GlobalEnv)
    # if ( exists("Transcripts", envir=epiSeekerEnv, inherits=FALSE) ) {
    #     features <- get("Transcripts", envir=epiSeekerEnv)
    # } else {
    #     features <- transcriptsBy(TxDb)
    #     features <- unlist(features)
    #     assign("Transcripts", features, envir=epiSeekerEnv)
    # }

    features <- get_cache_element(item = epiSeekerCache, elements = "Transcripts")
    if (is.null(features)) {
        features <- transcriptsBy(TxDb)
        features <- unlist(features)
        update_cache_item(item = epiSeekerCache, list("Transcripts" = features))
    }

    ol <- lapply(target.anno, function(i) unique(intersect(as.GRanges(query.anno)$geneId, as.GRanges(i)$geneId)))
    oln <- unlist(lapply(ol, length))
    N <- length(features)
    ## white ball
    m <- length(unique(as.GRanges(query.anno)$geneId))
    ## black ball
    n <- N - m
    ## drawn
    k <- unlist(lapply(target.anno, function(i) length(unique(as.GRanges(i)$geneId))))
    p <- phyper(oln, m, n, k, lower.tail = FALSE)


    if (is(queryPeak, "GRanges")) {
        qSample <- "queryPeak"
    } else {
        qSample <- basename(queryPeak)
    }

    if (is.null(targetFiles)) {
        tSample <- names(target.gr)
        if (is.null(tSample)) {
            tSample <- paste0("targetPeak", seq_along(target.gr))
        }
    } else {
        tSample <- basename(targetFiles)
    }

    padj <- p.adjust(p, method = pAdjustMethod)
    res <- data.frame(
        qSample = qSample,
        tSample = tSample,
        qLen = length(unique(as.GRanges(query.anno)$geneId)),
        tLen = unlist(lapply(target.anno, function(i) length(unique(as.GRanges(i)$geneId)))),
        N_OL = oln,
        pvalue = p,
        p.adjust = padj
    )
    return(res)
}

#' calculate overlap significant of ChIP experiments based on the genome coordinations
#'
#' The observed quantity is the fraction of \emph{target} peaks covered by the
#' query peaks (`N_OL / length(targetPeak)`) and the null distribution is
#' generated by shuffling the \emph{target} peaks, i.e. the test answers "are the
#' query peaks enriched within the target peaks?". `N_OL` itself is symmetric (the
#' same number is reported in both directions), but the p-value is not:
#' exchanging `queryPeak` and `targetPeak` asks the mirrored question and
#' normalises by the other peak set, so the p-values can differ substantially
#' when the two peak sets differ in size. Even for equally sized sets the two
#' null distributions are sampled independently, which leaves small Monte-Carlo
#' differences (see issue #84 of ChIPseeker). Compare `N_OL` directly if a
#' direction-free measure is needed, and increase `nShuffle` to reduce the
#' Monte-Carlo part.
#'
#' Strand is ignored by every method and every column: a peak overlaps a target region
#' whatever the strand of either, as for peaks of DNA-based assays, which have none.
#' Annotation sets used as targets (genes, transposable elements) usually carry `+`/`-`
#' strand, and the shuffled sets of the null distribution have none, so the observed
#' overlap is counted without strand as well (earlier versions counted it with strand and
#' reported `N_OL = 0` and `p = 1` for a stranded target set). For a strand-specific
#' question, split both sets by strand and call the function once per strand.
#'
#' @title enrichPeakOverlap
#' @param queryPeak query bed file or GRanges object
#' @param targetPeak target bed file(s) or folder that containing bed files or a list of GRanges objects
#' @param TxDb TxDb
#' @param pAdjustMethod pvalue adjustment method
#' @param nShuffle shuffle numbers
#' @param chainFile chain file for liftOver
#' @param pool logical, whether pool target peaks. With `pool = TRUE` one null
#'   distribution is drawn by shuffling a randomly chosen target set at a time, so
#'   target sets of different sizes share it; with `pool = FALSE` each target set
#'   gets its own null. Ignored when `background` is given (each target set then
#'   has its own null)
#' @param mc.cores number of cores, see \link[parallel]{mclapply}
#' @param verbose logical
#' @param symmetric logical, whether the p-value should be direction free.
#'   Default is FALSE, which reports the one-sided test described above. If
#'   TRUE, the mirrored direction (query and target exchanged) is computed as
#'   well and the two are combined as `min(1, 2*min(p, p_rev))` (Hedges), so that
#'   the result does not depend on the order of the arguments. Note that this
#'   doubles the number of permutations and that the smallest reportable p-value
#'   becomes `2/(nShuffle+1)`; use a larger `nShuffle` and `set.seed()` for a
#'   reproducible result (issue #84 of ChIPseeker)
#' @param background regions the target peaks are shuffled into under the null
#'   (a `GRanges` or a bed file, in the coordinates of `queryPeak`), for example
#'   open chromatin, mappable regions or, for RNA modifications, exons. Default
#'   `NULL` shuffles over whole chromosomes. Peaks of real assays sit in a small
#'   part of the genome, so two unrelated peak sets overlap far more than peaks
#'   spread over whole chromosomes would, and almost every target set comes out
#'   "significant"; shuffling within a background that matches the data removes
#'   that. When given, each target set gets its own null: its peaks are moved to
#'   random positions in the background, chosen by base pair, keeping their widths
#'   and the number of peaks per chromosome (peaks on a chromosome without
#'   background go anywhere in it), and
#'   p = (#\{null >= observed\} + 1) / (nShuffle + 1). With `symmetric = TRUE` the
#'   mirrored direction shuffles the query peaks within the background
#'
#'   Without `background`, the first call of a session says so in a message (the
#'   p-values of a whole-genome null are anti-conservative for peaks concentrated in open
#'   chromatin: on 20 ENCODE TF ChIP-seq peak sets against 60 reference sets, 1181 of the
#'   1200 pairs were significant). `verbose = FALSE` or
#'   `options(epiSeeker.null_note = FALSE)` turns it off
#' @param method `"permutation"` (default) or `"fisher"`. `"fisher"` needs `background`,
#'   which it uses as the universe, and makes no permutations (`nShuffle` is ignored): the
#'   units are the background regions (overlapping ones merged, adjacent ones kept apart, so
#'   tiles stay tiles) plus every query region that overlaps
#'   none of them; for each target set the units hit by both sets, by one or by neither form
#'   a 2x2 table, and the one-sided Cochran-Mantel-Haenszel test over `strata` bins of unit
#'   width gives the p-value (with `strata = 1`, Fisher's exact test). Stratifying by width
#'   matters: wide units are hit by both sets more often by chance, which makes an
#'   unstratified region-level test (as LOLA's) anti-conservative on universes of unequal
#'   region sizes. It is much faster than the permutation test
#' @param strata number of bins of unit width (quantiles of log width) for the region-level
#'   test and the `odds_ratio` column; default 50 (units of identical width share a bin, so
#'   there can be fewer)
#' @return a `peakOverlapResult`, which is a data.frame with one row per target peak set:
#'   `qSample`, `tSample`, `qLen`, `tLen`, `N_OL`, `pvalue`, `p.adjust`, and three effect
#'   sizes that need no permutation: `jaccard` (shared base pairs over the base pairs of the
#'   union), `frac_query` (fraction of query peaks overlapping the target set) and
#'   `frac_target` (fraction of target peaks overlapping the query). Strand is ignored
#'   throughout (see Details). With a null distribution (`nShuffle > 0`) also `expected`, the mean
#'   N_OL under the null, and `fold_enrichment` = N_OL / expected, which corrects for the
#'   size of each target set (and, with `background`, for where peaks can be). The p-value
#'   cannot rank target sets against each other: its smallest value, 1/(nShuffle+1), is
#'   shared by most of them; rank by `jaccard` instead (on those 20 ENCODE peak sets it put
#'   the profiled factor first for 11 of 14, `fold_enrichment` for 3-4), and report
#'   `fold_enrichment` as an effect size. With `background` also `odds_ratio`, the
#'   Mantel-Haenszel odds ratio of the region-level table described under `method` (`NA`
#'   without a background); against the union of those reference sets as background it put
#'   the profiled factor first for 13 of 14, but in simulation it ranked a weakly shared
#'   true set below related or small sets more often than `jaccard`, so `rank_by` stays
#'   `jaccard`. The
#'   adjusted p-values are corrected across all target sets, for `pool = FALSE` as well. The
#'   arguments the p-values were computed with, and the statistic the results should be
#'   ranked by (`rank_by`), are in `attr(, "params")`.
#' @export
#' @examples
#' require(TxDb.Hsapiens.UCSC.hg38.knownGene)
#' txdb <- TxDb.Hsapiens.UCSC.hg38.knownGene
#' peakfile <- system.file("extdata", "demo_peak.txt", package = "epiSeeker")
#' peak <- readPeakFile(peakfile)[1:10]
#' enrichPeakOverlap(peak, peakfile, txdb, mc.cores = 1, nShuffle = 20)
#' @importFrom rtracklayer import.chain
#' @importFrom rtracklayer liftOver
#' @author G Yu
enrichPeakOverlap <- function(queryPeak, targetPeak, TxDb = NULL, pAdjustMethod = "BH", nShuffle = 1000,
                              chainFile = NULL, pool = TRUE, mc.cores = detectCores() - 1, verbose = TRUE,
                              symmetric = FALSE, background = NULL,
                              method = c("permutation", "fisher"), strata = 50) {
    method <- match.arg(method)
    if (method == "fisher" && is.null(background)) {
        stop("method = \"fisher\" needs `background`, the universe the test counts regions in ",
             "(for example open chromatin of the cell type).")
    }
    TxDb <- loadTxDb(TxDb)
    query.gr <- loadPeak(queryPeak)
    if (is(targetPeak[1], "GRanges") || is(targetPeak[[1]], "GRanges")) {
        ## a single GRanges (or a list of GRanges) is accepted; a bare GRanges
        ## has to be wrapped in a list, the overlap code below works on a list
        ## of target peak sets and used to fail with
        ## "GRanges objects don't support [[, as.list(), lapply()"
        target.gr <- if (is(targetPeak, "GRanges")) list(targetPeak) else targetPeak
        targetFiles <- NULL
    } else {
        targetFiles <- parse_targetPeak_Param(targetPeak)
        target.gr <- lapply(targetFiles, loadPeak)
    }

    if (!is.null(chainFile)) {
        chain <- import.chain(chainFile)
        target.gr <- lapply(target.gr, liftOver, chain = chain)
    }

    ## Strand is ignored by every method (see Details). The observed overlap used to keep
    ## strand (intersect() pairs "*" only with "*") while the shuffled sets were unstranded,
    ## so a target set with +/- strand (genes, TEs) gave N_OL = 0 and p = 1 without a warning.
    query.gr <- .unstrand_gr(query.gr)
    target.gr <- lapply(target.gr, .unstrand_gr)

    if (is(queryPeak, "GRanges")) {
        qSample <- "queryPeak"
    } else {
        ## remove path, only keep file name
        qSample <- basename(queryPeak)
    }

    if (is.null(targetFiles)) {
        tSample <- names(target.gr)
        if (is.null(tSample)) {
            tSample <- paste0("targetPeak", seq_along(target.gr))
        }
    } else {
        tSample <- basename(targetFiles)
    }

    if (is.null(background) && nShuffle >= 1 && verbose) .note_whole_genome_null()

    ## region-level 2x2 against the background: the odds ratio for every call with a
    ## background, and the test itself for method = "fisher"
    ft <- if (!is.null(background)) .overlap_fisher(query.gr, target.gr, background, strata) else NULL

    if (method == "fisher") {
        es <- .overlap_effect_size(query.gr, target.gr)
        res <- data.frame(
            qSample = qSample,
            tSample = tSample,
            qLen = length(query.gr),
            tLen = unlist(lapply(target.gr, length)),
            N_OL = .n_intersect(query.gr, target.gr),
            pvalue = ft$pvalue,
            p.adjust = p.adjust(ft$pvalue, method = pAdjustMethod),
            expected = ft$expected,
            fold_enrichment = ft$a / ft$expected,
            odds_ratio = ft$odds_ratio,
            jaccard = es$jaccard,
            frac_query = es$frac_query,
            frac_target = es$frac_target
        )
        return(.as_peakOverlapResult(res, nShuffle = 0, pool = pool, symmetric = symmetric,
                                     pAdjustMethod = pAdjustMethod, chainFile = chainFile, TxDb = TxDb,
                                     null = .fisher_null_label(ft), method = method, fisher = ft))
    }

    if (!is.null(background)) {
        bg <- .prepare_background(background)
        p.ol <- .overlap_perm_background(query.gr, target.gr, bg, nShuffle,
                                         mc.cores = mc.cores, verbose = verbose)
        null <- "per target set, shuffled within background"
    } else if (pool) {
        p.ol <- enrichOverlap.peak.internal(query.gr, target.gr, TxDb, nShuffle,
            mc.cores = mc.cores, verbose = verbose
        )
        null <- "pooled over target sets, shuffled over whole chromosomes"
    } else {
        ## one call per target set. The target is passed with its name, which was
        ## lost before (every row was "targetPeak1"), and the adjustment is made
        ## here across all target sets: inside each call p.adjust() saw one p-value
        res_list <- lapply(seq_len(length(target.gr)), function(i) {
            enrichPeakOverlap(
                queryPeak = queryPeak,
                targetPeak = stats::setNames(target.gr[i], tSample[i]),
                TxDb = TxDb,
                pAdjustMethod = pAdjustMethod,
                nShuffle = nShuffle,
                chainFile = NULL,
                mc.cores = mc.cores,
                verbose = verbose,
                symmetric = symmetric
            )
        })
        res <- do.call("rbind", lapply(res_list, as.data.frame))
        res$p.adjust <- if (all(is.na(res$pvalue))) NA else p.adjust(res$pvalue, method = pAdjustMethod)
        return(.as_peakOverlapResult(res, nShuffle = nShuffle, pool = pool, symmetric = symmetric,
                                     pAdjustMethod = pAdjustMethod, chainFile = chainFile, TxDb = TxDb,
                                     null = "per target set, shuffled over whole chromosomes"))
    }

    if (is.null(p.ol$pvalue)) {
        p <- padj <- NA
    } else {
        p <- p.ol$pvalue
        if (symmetric) {
            ## combine the one-sided test with the mirrored direction (query and
            ## target exchanged) as min(1, 2*min(p, p_rev)); see the 'Direction of
            ## the test' section of the documentation
            p.rev <- if (is.null(background)) {
                enrichOverlap.peak.mirrored(query.gr, target.gr, TxDb,
                                            nShuffle, mc.cores = mc.cores,
                                            verbose = verbose
                )$pvalue
            } else {
                .overlap_perm_background(query.gr, target.gr, bg, nShuffle, mc.cores = mc.cores,
                                         verbose = verbose, shuffle_query = TRUE)$pvalue
            }
            p <- pmin(1, 2 * pmin(p, p.rev))
        }
        padj <- p.adjust(p, method = pAdjustMethod)
    }

    ol <- p.ol$overlap
    expected <- if (is.null(p.ol$expected)) NA_real_ else p.ol$expected

    es <- .overlap_effect_size(query.gr, target.gr)
    res <- data.frame(
        qSample = qSample,
        tSample = tSample,
        qLen = length(query.gr),
        tLen = unlist(lapply(target.gr, length)),
        N_OL = ol,
        pvalue = p,
        p.adjust = padj,
        expected = expected,
        fold_enrichment = ol / expected,
        odds_ratio = if (is.null(ft)) NA_real_ else ft$odds_ratio,
        jaccard = es$jaccard,
        frac_query = es$frac_query,
        frac_target = es$frac_target
    )

    .as_peakOverlapResult(res, nShuffle = nShuffle, pool = pool, symmetric = symmetric,
                          pAdjustMethod = pAdjustMethod, chainFile = chainFile, TxDb = TxDb,
                          null = null, method = method, fisher = ft)
}

## Once per session (rlang's frequency = "once"); the recursive calls of pool = FALSE share it.
.note_whole_genome_null <- function() {
    if (isFALSE(getOption("epiSeeker.null_note", TRUE))) return(invisible())
    rlang::inform(c(
        "The p-values come from shuffling over whole chromosomes (`background = NULL`).",
        i = paste("For peaks concentrated in open chromatin this null is anti-conservative: almost",
                  "every target set comes out significant."),
        i = paste("Give `background =` (e.g. open chromatin of the cell type) for calibrated p-values,",
                  "and rank target sets by `jaccard`."),
        i = "Turn this note off with verbose = FALSE or options(epiSeeker.null_note = FALSE)."
    ), .frequency = "once", .frequency_id = "epiSeeker_whole_genome_null")
}

## strand set to "*" (mcols kept): peak overlap ignores strand
.unstrand_gr <- function(gr) {
    strand(gr) <- "*"
    gr
}

## Effect sizes that do not depend on a null distribution, one row per target set:
## base-pair Jaccard of the reduced sets, and the fraction of query (target) peaks that
## overlap the other set. Strand is ignored. Unlike the p-value, whose smallest value
## 1/(nShuffle+1) is shared by most target sets, these can rank the targets.
.overlap_effect_size <- function(query.gr, target.gr) {
    ## computed from the overlapping pairs of the reduced sets: within a reduced set no two
    ## regions overlap or touch, so the pairwise intersections are the pieces of
    ## intersect(q, t), and union = |q| + |t| - intersection (same values as with
    ## union()/intersect(), much faster on many target sets)
    unstrand <- function(gr) { strand(gr) <- "*"; granges(gr) }
    qu <- unstrand(query.gr)
    q <- GenomicRanges::reduce(qu)
    wq <- sum(as.numeric(width(q)))
    one <- function(tt) {
        tu <- unstrand(tt)
        t <- GenomicRanges::reduce(tu)
        h <- GenomicRanges::findOverlaps(q, t)
        i <- sum(as.numeric(width(GenomicRanges::pintersect(q[S4Vectors::queryHits(h)],
                                                          t[S4Vectors::subjectHits(h)]))))
        u <- wq + sum(as.numeric(width(t))) - i
        c(jaccard = if (u > 0) i / u else NA_real_,
          frac_query = if (length(qu)) mean(IRanges::overlapsAny(qu, t)) else NA_real_,
          frac_target = if (length(tu)) mean(IRanges::overlapsAny(tu, q)) else NA_real_)
    }
    ## a target set on other chromosomes simply shares nothing (jaccard 0); GenomicRanges
    ## warns "no sequence levels in common" for it, which says nothing the 0 does not
    m <- withCallingHandlers(vapply(target.gr, one, numeric(3)), warning = function(w) {
        if (grepl("no sequence levels in common", conditionMessage(w))) invokeRestart("muffleWarning")
    })
    list(jaccard = unname(m["jaccard", ]), frac_query = unname(m["frac_query", ]),
         frac_target = unname(m["frac_target", ]))
}

## length(intersect(query.gr, tt, ignore.strand = TRUE)) for every target set, from the
## overlapping pairs of the reduced sets (strand ignored, as everywhere in enrichPeakOverlap())
.n_intersect <- function(query.gr, target.gr) {
    q <- GenomicRanges::reduce(granges(query.gr), ignore.strand = TRUE)
    one <- function(tt) {
        t <- GenomicRanges::reduce(granges(tt), ignore.strand = TRUE)
        as.numeric(length(GenomicRanges::findOverlaps(q, t, ignore.strand = TRUE)))
    }
    withCallingHandlers(vapply(target.gr, one, numeric(1)), warning = function(w) {
        if (grepl("no sequence levels in common", conditionMessage(w))) invokeRestart("muffleWarning")
    })
}

setOldClass(c("peakOverlapResult", "data.frame"))

## The result stays a data.frame (existing code keeps working); the class lets methods
## recognise it and the attribute records how the p-values were obtained.
.as_peakOverlapResult <- function(res, nShuffle, pool, symmetric, pAdjustMethod, chainFile, TxDb,
                                  null = NA_character_, method = "permutation", fisher = NULL) {
    genome <- tryCatch(paste(unique(stats::na.omit(GenomeInfoDb::genome(TxDb))), collapse = ","),
                       error = function(e) NA_character_)
    if (is.null(res$odds_ratio)) res$odds_ratio <- NA_real_
    attr(res, "params") <- list(nShuffle = nShuffle, pool = pool, symmetric = symmetric,
                                pAdjustMethod = pAdjustMethod, liftOver = !is.null(chainFile),
                                genome = genome, null = null, method = method, strand = "ignored",
                                strata = if (is.null(fisher)) NA_integer_ else fisher$strata,
                                universe_units = if (is.null(fisher)) NA_integer_ else fisher$units,
                                query_outside_universe = if (is.null(fisher)) NA_integer_ else fisher$query_outside,
                                target_outside_universe = if (is.null(fisher)) NA_integer_ else fisher$target_outside,
                                rank_by = .default_rank_by(res))
    class(res) <- c("peakOverlapResult", "data.frame")
    res
}

## The statistic target sets are ranked by (see the documentation of enrichPeakOverlap()).
.default_rank_by <- function(res) {
    "jaccard"
}

.fisher_null_label <- function(ft) {
    sprintf(paste("region-level test against the background: %d units (%d query regions outside it",
                  "added as units), Cochran-Mantel-Haenszel over %d width strata"),
            ft$units, ft$query_outside, ft$strata)
}

## Region-level 2x2 of every target set against a universe (LOLA's design), stratified by
## the width of the universe regions. Units are the regions of reduce(background,
## min.gapwidth = 0) plus every
## query region that overlaps none of them, so each query region falls in a unit and the
## counts are consistent (LOLA's raw mode fails with "Negative b entry" when query regions
## lie outside the universe). A unit is hit when it overlaps at least one region of the set
## (strand ignored); a = hit by both, b = target only, c = query only, d = neither. Wide
## units are hit by both sets more often by chance, so width confounds a plain 2x2: units
## are grouped into `strata` bins by quantiles of log width and combined with the
## Mantel-Haenszel odds ratio and the one-sided Cochran-Mantel-Haenszel test (continuity
## corrected). With strata = 1 the p-value is the exact hypergeometric tail (Fisher's exact
## test, alternative "greater") and the odds ratio the sample odds ratio.
.overlap_fisher <- function(query.gr, target.gr, background, strata = 50) {
    unstrand <- function(gr) { strand(gr) <- "*"; granges(gr) }
    bg <- if (is(background, "GRanges")) background else loadPeak(background)
    ## overlapping background regions are merged, adjacent ones are not: a universe of
    ## genome tiles must stay one unit per tile (merging adjacent tiles left one unit per
    ## chromosome)
    units <- GenomicRanges::reduce(unstrand(bg), min.gapwidth = 0L)
    q <- unstrand(query.gr)
    out_q <- !IRanges::overlapsAny(q, units)
    if (any(out_q)) {
        units <- c(units, GenomicRanges::reduce(q[out_q]))
    }
    n_units <- length(units)
    strata <- max(1L, as.integer(strata))
    lw <- log(as.numeric(width(units)))
    br <- unique(stats::quantile(lw, probs = seq(0, 1, length.out = strata + 1), names = FALSE))
    s <- if (length(br) > 2) cut(lw, br, include.lowest = TRUE, labels = FALSE) else rep(1L, n_units)
    S <- max(s)
    hq <- IRanges::overlapsAny(units, q)
    idx <- GenomicRanges::GNCList(units)
    one <- function(tt) {
        tt <- unstrand(tt)
        ht <- IRanges::overlapsAny(units, tt)
        out_t <- sum(!IRanges::overlapsAny(tt, idx))
        ## doubles: products of four integer counts overflow on universes of ~10^4 units
        a <- as.numeric(tabulate(s[hq & ht], S)); b <- as.numeric(tabulate(s[!hq & ht], S))
        cc <- as.numeric(tabulate(s[hq & !ht], S)); d <- as.numeric(tabulate(s[!hq & !ht], S))
        n <- a + b + cc + d
        e <- (a + b) * (a + cc) / n
        if (S == 1) {
            p <- stats::phyper(a - 1, a + cc, b + d, a + b, lower.tail = FALSE)
            return(c(p, (a * d) / (b * cc), a, e, out_t))
        }
        k <- n > 1
        v <- (a + b) * (cc + d) * (a + cc) * (b + d) / (n^2 * (n - 1))
        sv <- sum(v[k])
        p <- if (sv > 0) stats::pnorm((sum(a[k]) - sum(e[k]) - 0.5) / sqrt(sv), lower.tail = FALSE) else 1
        or <- sum((a * d / n)[n > 0]) / sum((b * cc / n)[n > 0])
        c(p, or, sum(a), sum(e[n > 0]), out_t)
    }
    m <- vapply(target.gr, one, numeric(5))
    list(pvalue = unname(m[1, ]), odds_ratio = unname(m[2, ]), a = unname(m[3, ]),
         expected = unname(m[4, ]), strata = S, units = n_units, query_outside = sum(out_q),
         target_outside = sum(m[5, ]))
}


#' shuffle the position of peak
#'
#'
#' @title shuffle
#' @param peak.gr GRanges object
#' @param TxDb TxDb
#' @return GRanges object
#' @export
#' @examples
#' require(TxDb.Hsapiens.UCSC.hg38.knownGene)
#' txdb <- TxDb.Hsapiens.UCSC.hg38.knownGene
#' p <- GRanges(
#'     seqnames = c("chr1", "chr3"),
#'     ranges = IRanges(start = c(1, 100), end = c(50, 130))
#' )
#' shuffle(p, TxDb = txdb)
#' @author G Yu
shuffle <- function(peak.gr, TxDb) {
    nn <- as.vector(seqnames(peak.gr))
    ii <- order(nn)
    w <- width(peak.gr)
    nnt <- table(nn)
    jj <- order(names(nnt))
    nnt <- nnt[jj]
    ## lengths by chromosome name. They were taken in the order of seqlevels(peak.gr)
    ## and paired by position with the alphabetical names of table(), so with
    ## seqlevels chr1, chr2, ..., chr10 the peaks of chr10 were placed along the
    ## length of chr2. Identical to before when the seqlevels are the chromosomes
    ## with peaks, sorted alphabetically (as readPeakFile() returns them).
    chrLens <- seqlengths(TxDb)[names(nnt)]
    ss <- unlist(lapply(seq_len(length(nnt)), function(i) sample(chrLens[i], nnt[i])))

    res <- GRanges(seqnames = nn[ii], ranges = IRanges(ss, width = w[ii]), strand = "*")
    return(res)
}


#' @import GenomeInfoDb
#' @importFrom utils txtProgressBar
#' @importFrom utils setTxtProgressBar
#' @importFrom parallel mclapply
#' @importFrom parallel detectCores
enrichOverlap.peak.internal <- function(query.gr, target.gr, TxDb, nShuffle = 1000, mc.cores = detectCores() - 1, verbose = TRUE) {
    if (verbose) {
        message(
            ">> permutation test of peak overlap...\t\t",
            format(Sys.time(), "%Y-%m-%d %X"), "\n"
        )
    }

    idx <- sample(seq_len(length(target.gr)), nShuffle, replace = TRUE)
    len <- unlist(lapply(target.gr, length))

    if (Sys.info()[1] == "Windows") {
        qLen <- lapply(target.gr, function(tt) {
            length(intersect(query.gr, tt, ignore.strand = TRUE))
        })
    } else {
        qLen <- mclapply(target.gr, function(tt) {
            length(intersect(query.gr, tt, ignore.strand = TRUE))
        }, mc.cores = mc.cores)
    }
    qLen <- unlist(qLen)
    ## query ratio
    qr <- qLen / len

    if (nShuffle < 1) {
        res <- list(pvalue = NULL, overlap = qLen)
        return(res)
    }

    if (verbose) {
        pb <- txtProgressBar(min = 0, max = nShuffle, style = 3)
    }
    if (Sys.info()[1] == "Windows") {
        rr <- lapply(seq_along(idx), function(j) {
            if (verbose) {
                setTxtProgressBar(pb, j)
            }
            i <- idx[j]
            tarShuffle <- shuffle(target.gr[[i]], TxDb)
            length(intersect(query.gr, tarShuffle, ignore.strand = TRUE)) / len[i]
        })
    } else {
        rr <- mclapply(seq_along(idx), function(j) {
            if (verbose) {
                setTxtProgressBar(pb, j)
            }
            i <- idx[j]
            tarShuffle <- shuffle(target.gr[[i]], TxDb)
            length(intersect(query.gr, tarShuffle, ignore.strand = TRUE)) / len[i]
        }, mc.cores = mc.cores)
    }

    if (verbose) {
        close(pb)
    }

    rr <- unlist(rr) ## random ratio

    ## p <- lapply(qr, function(q) mean(rr>q))
    ## a null value equal to the observed one counts against it: with `>` ties were left
    ## out, and for small target sets, where the overlap is a small integer and ties are
    ## common, 20% of unrelated sets came out at p < 0.05
    p <- lapply(qr, function(q) (sum(rr >= q) + 1) / (length(rr) + 1))
    ## mean overlap under the pooled null, scaled to the size of each target set
    res <- list(pvalue = unlist(p), overlap = qLen, expected = unname(mean(rr) * len))
    return(res)
}

## background for shuffling: reduced, strand ignored, indexed by chromosome once
.prepare_background <- function(background) {
    bg <- if (is(background, "GRanges")) background else loadPeak(background)
    bg <- GenomicRanges::reduce(bg, ignore.strand = TRUE)
    if (!length(bg)) stop("`background` contains no regions.")
    chr <- as.character(seqnames(bg))
    by_chr <- split(seq_along(chr), chr)
    w <- as.numeric(width(bg))
    ## cumulative widths per chromosome (and over the whole background), so that a position
    ## is drawn by base pair with findInterval() instead of a weighted sample() per call
    list(chr = chr, start = start(bg), width = width(bg), by_chr = by_chr,
         cum = lapply(by_chr, function(k) cumsum(w[k])), cum_all = cumsum(w))
}

## Move every peak to a random position in the background, chosen by base pair: a
## background region is drawn with probability proportional to its width and the peak
## placed uniformly within it. Widths and the number of peaks per chromosome are kept;
## a peak on a chromosome without background goes anywhere in the background, and a
## peak wider than its region starts at the region start.
.shuffle_in_background <- function(peak.gr, bg) {
    chr <- as.character(seqnames(peak.gr))
    w <- width(peak.gr)
    out_chr <- chr
    out_start <- integer(length(chr))
    for (cc in unique(chr)) {
        i <- which(chr == cc)
        k <- bg$by_chr[[cc]]
        cw <- bg$cum[[cc]]
        if (is.null(k)) { k <- seq_along(bg$chr); cw <- bg$cum_all }
        ## a background region with probability proportional to its width
        j <- k[findInterval(stats::runif(length(i)) * cw[length(cw)], cw) + 1L]
        room <- pmax(bg$width[j] - w[i] + 1L, 1L)
        out_start[i] <- bg$start[j] + as.integer(floor(stats::runif(length(i)) * room))
        out_chr[i] <- bg$chr[j]
    }
    GRanges(out_chr, IRanges(out_start, width = w), strand = "*")
}

## Permutation test with one null per target set, shuffling the target set (or, for the
## mirrored direction, the query) within the background. Returns, per target set, the
## p-value (#{null >= observed} + 1) / (nShuffle + 1), the observed overlap and its mean
## under the null.
.overlap_perm_background <- function(query.gr, target.gr, bg, nShuffle, mc.cores = 1,
                                     verbose = TRUE, shuffle_query = FALSE) {
    if (verbose) {
        message(">> permutation test of peak overlap within the background",
                if (shuffle_query) " (mirrored)", "...\t", format(Sys.time(), "%Y-%m-%d %X"))
    }
    ## All target sets are handled together in each permutation: they are concatenated
    ## once, shuffled in one call, reduced per set and counted against the reduced query
    ## with one overlap search. The count is the number of overlapping pairs of reduced
    ## query and reduced target regions, which equals length(intersect(query, target)):
    ## reduced regions are never adjacent, so no two pieces of the intersection merge.
    ## Strand is ignored throughout.
    unstrand <- function(gr) { strand(gr) <- "*"; granges(gr) }
    n_t <- length(target.gr)
    grp <- rep(seq_len(n_t), lengths(target.gr))
    t_all <- unstrand(do.call(c, unname(lapply(target.gr, granges))))
    q_red <- GenomicRanges::reduce(unstrand(query.gr))
    q_idx <- GenomicRanges::GNCList(q_red)
    count_t <- function(t_gr) {
        tl <- GenomicRanges::reduce(split(t_gr, factor(grp, levels = seq_len(n_t))))
        h <- IRanges::countOverlaps(unlist(tl, use.names = FALSE), q_idx)
        vapply(split(h, factor(rep(seq_len(n_t), lengths(tl)), levels = seq_len(n_t))), sum, numeric(1))
    }
    t_red <- GenomicRanges::reduce(split(t_all, factor(grp, levels = seq_len(n_t))))
    t_red_all <- unlist(t_red, use.names = FALSE)
    t_red_grp <- factor(rep(seq_len(n_t), lengths(t_red)), levels = seq_len(n_t))
    obs <- unname(count_t(t_all))
    if (nShuffle < 1) {
        return(list(pvalue = NULL, overlap = obs, expected = NULL))
    }
    one <- function(j) {
        if (shuffle_query) {
            qs <- GenomicRanges::reduce(.shuffle_in_background(query.gr, bg))
            vapply(split(IRanges::countOverlaps(t_red_all, qs), t_red_grp), sum, numeric(1))
        } else {
            count_t(.shuffle_in_background(t_all, bg))
        }
    }
    rr <- if (Sys.info()[1] == "Windows" || mc.cores <= 1) {
        lapply(seq_len(nShuffle), one)
    } else {
        mclapply(seq_len(nShuffle), one, mc.cores = mc.cores)
    }
    rr <- matrix(unlist(rr), nrow = length(target.gr))
    list(pvalue = unname((rowSums(rr >= obs) + 1) / (nShuffle + 1)),
         overlap = unname(obs), expected = unname(rowMeans(rr)))
}

#' Mirrored permutation test of peak overlap
#'
#' The same permutation test as `enrichOverlap.peak.internal()`, but with the
#' roles of the two peak sets exchanged: the *target* peaks are kept fixed and
#' the whole *query* set is shuffled in each permutation, and the overlap with
#' each target set is compared with its overlap under the null. It is the second
#' half of the two-sided (symmetric) p-value of
#' `enrichPeakOverlap(symmetric = TRUE)` (issue #84 of ChIPseeker).
#'
#' @param query.gr GRanges of the query peaks
#' @param target.gr list of GRanges, one element per target peak set
#' @param TxDb TxDb object, provides the chromosome lengths for shuffling
#' @param nShuffle integer, number of permutations
#' @param mc.cores integer, number of cores
#' @param verbose logical
#' @return list with the `pvalue` of every target peak set and the number of
#'   overlapping query peaks
#' @importFrom utils txtProgressBar
#' @importFrom utils setTxtProgressBar
#' @importFrom parallel mclapply
#' @noRd
#' @author G Yu
enrichOverlap.peak.mirrored <- function(query.gr, target.gr, TxDb, nShuffle = 1000,
                                         mc.cores = detectCores() - 1, verbose = TRUE) {
    if (verbose) {
        cat(">> permutation test of peak overlap (mirrored)...\t",
            format(Sys.time(), "%Y-%m-%d %X"), "\n",
            sep = ""
        )
    }

    obs <- unlist(lapply(target.gr, function(tt) {
        length(intersect(query.gr, tt, ignore.strand = TRUE))
    }))

    if (nShuffle < 1) {
        return(list(pvalue = NULL, overlap = obs))
    }

    if (verbose) {
        pb <- txtProgressBar(min = 0, max = nShuffle, style = 3)
    }

    shuffleOne <- function(j) {
        if (verbose) {
            setTxtProgressBar(pb, j)
        }
        ## the whole query set. One peak, query.gr[idx[j]], was shuffled before and its
        ## overlap (0 or 1) compared with the observed ratio, so the null did not depend
        ## on the data: two sets with no overlap at all came out at p = 0.02
        qShuffle <- shuffle(query.gr, TxDb)
        unlist(lapply(target.gr, function(tt) length(intersect(qShuffle, tt, ignore.strand = TRUE))))
    }

    if (Sys.info()[1] == "Windows") {
        rr <- lapply(seq_len(nShuffle), shuffleOne)
    } else {
        rr <- mclapply(seq_len(nShuffle), shuffleOne, mc.cores = mc.cores)
    }

    if (verbose) {
        close(pb)
    }

    rr <- matrix(unlist(rr), nrow = length(target.gr))
    ## count with count; ties count against the observed overlap
    p <- (rowSums(rr >= obs) + 1) / (nShuffle + 1)

    res <- list(pvalue = unname(p), overlap = obs)
    return(res)
}
